function makeToolName(endpoint) {
  const base = endpoint.operationId || `${endpoint.method}-${endpoint.path}`;
  return capToolName(`official_${endpoint.app}_${base}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .replace(/_+/g, '_'));
}

function capToolName(name) {
  const maxLength = 64;
  if (name.length <= maxLength) return name;

  const suffix = createHash('sha1').update(name).digest('hex').slice(0, 6);
  const prefixLength = maxLength - suffix.length - 1;
  const prefix = name.slice(0, prefixLength).replace(/_+$/g, '');
  return `${prefix}_${suffix}`;
}

function dedupeToolNames(items) {
  const counts = new Map();
  for (const item of items) {
    const count = counts.get(item.name) || 0;
    counts.set(item.name, count + 1);
    if (count > 0) {
      // Re-apply the cap so the dedupe suffix doesn't push past 64 chars.
      item.name = capToolName(`${item.name}_${count + 1}`);
    }
  }
}

/**
 * Derive the access-level requirement from an endpoint's security scheme names.
 * Mirrors GHL v3's security components:
 *   Agency-Access-Only   → requires an Agency/Company token
 *   Location-Access-Only → requires a Location token
 *   anything else        → accepts either
 */
function deriveAccessLevel(securitySchemes) {
  const schemes = securitySchemes || [];
  const hasAgencyOnly = schemes.includes('Agency-Access-Only');
  const hasLocationOnly = schemes.includes('Location-Access-Only');
  // If an endpoint accepts BOTH -Only schemes, it accepts either token type.
  if (hasAgencyOnly && hasLocationOnly) return 'any';
  if (hasAgencyOnly) return 'agency-only';
  if (hasLocationOnly) return 'location-only';
  return 'any';
}

function getPathParams(path) {
  return [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
}

function getOperation(endpoint) {
  if (!endpoint.sourceFile || !endpoint.sourceFile.endsWith('.json')) return undefined;
  // sourceFile is relative to the docs repo root, e.g. "apps/contacts.json"
  // or "apps/v3/contacts-v3.json".
  const specPath = join(repoRoot, 'tmp', 'highlevel-api-docs', endpoint.sourceFile);
  let spec;
  try {
    spec = JSON.parse(readFileSync(specPath, 'utf8'));
  } catch {
    return undefined;
  }
  return spec.paths?.[endpoint.path]?.[endpoint.method.toLowerCase()];
}

function getParams(endpoint, paramLocation) {
  const operation = getOperation(endpoint);
  return (operation?.parameters || [])
    .filter((param) => param.in === paramLocation && param.name !== 'Version')
    .map((param) => ({
      name: param.name,
      required: Boolean(param.required),
      schema: param.schema ? sanitizeGeneratorSchema(param.schema) : undefined,
      description: param.description || undefined,
    }));
}

function getRequestBodySchema(endpoint) {
  const operation = getOperation(endpoint);
  const schema = operation?.requestBody?.content?.['application/json']?.schema;
  return schema ? sanitizeGeneratorSchema(schema) : undefined;
}

function sanitizeGeneratorSchema(schema) {
  const allowed = new Set(['type', 'enum', 'items', 'format', 'default', 'minimum', 'maximum', 'minLength', 'maxLength', '$ref', 'properties', 'required']);
  const clean = {};
  for (const [key, value] of Object.entries(schema || {})) {
    if (allowed.has(key)) clean[key] = value;
  }
  return clean;
}
